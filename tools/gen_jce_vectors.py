"""生成 JCE 金标向量 (vectors-jce.json)。

用参考实现 ysp-live-v9.5.py 里原封不动的 W / _qua / _head / _wrap 产出**真实字节**，
供 Java 侧 JceTest 做 byte-for-byte 断言。

用法: python C:\\1\\ysp-android\\tools\\gen_jce_vectors.py
"""
from __future__ import annotations

import importlib.util
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = os.path.join(ROOT, 'ysp-live-v9.5.py')
OUT = os.path.join(ROOT, 'tools', 'vectors-jce.json')


def load_ref():
    spec = importlib.util.spec_from_file_location('ysp_ref', REF)
    m = importlib.util.module_from_spec(spec)
    # dataclasses 需要能在 sys.modules 里找到自己的模块
    sys.modules['ysp_ref'] = m
    spec.loader.exec_module(m)
    return m


def _inner_hex(m, cmd: int, body: bytes, reqid: int) -> str:
    """复刻 _wrap 内部的 inner 明文（gzip 之前），用于分层定位差异。"""
    import struct as _s
    w = m.W()
    w.struct(lambda ww: m._head(ww, cmd, reqid), 0)
    w.bytes(body, 1)
    reqcmd = w.out()
    inner = bytearray([38]) + _s.pack('>i', len(reqcmd) + 17) + bytes([1]) + b'\x00' * 10 + reqcmd + bytes([40])
    return bytes(inner).hex()


def main() -> int:
    m = load_ref()

    # 固定 GUID，才能让 _qua 里的 GUID[:16] / GUID 字段可复现
    m.GUID = '00' * 16

    vectors = {
        '_note': 'generated by tools/gen_jce_vectors.py from ysp-live-v9.5.py; DO NOT EDIT',
        'guid': m.GUID,
        'verName': m.VER_NAME,
        'verCode': m.VER_CODE,
        'appId': m.APP_ID,
        'qmfAppId': m.QMF_APP_ID,
        'qmfPlatform': m.QMF_PLATFORM,
        'bizId': m.BIZ_ID,
        'chanId': m.CHAN_ID,
        'cases': [],
    }

    # ---------- 用例组 1: 时移请求体 + 整包 _wrap ----------
    cases = [
        # (label, cmd, reqid, pid, sid, start, end, stream)
        ('timeshift_default', 25312, 1700000012, '600001859', '2024078201', 1700000000, 1700000300, 'fhd'),
        ('timeshift_shd', 25312, 2147483647, '600099502', '2027249301', 1600000000, 1600003600, 'shd'),
        ('timeshift_zero', 25312, 0, '600002264', '2029810301', 0, 0, 'fhd'),
        # reqid 必须能塞进 int32（_head 用 w.int(reqid)），真实代码是 ts&0x7FFFFFFF
        ('timeshift_bignum', 25312, 1234567890, '600156816', '2026774101', 1900000000, 1900086400, 'fhd'),
        # 负时间戳 / 负数走 long 分支
        ('timeshift_negative', 25312, 1, '1', '2', -1, -86400, 'fhd'),
    ]
    for label, cmd, reqid, pid, sid, start, end, stream in cases:
        w = m.W()
        w.string(pid, 0)
        w.string(sid, 1)
        w.long(start, 2)
        w.long(end, 3)
        w.string(stream, 4)
        body = w.out()
        packet = m._wrap(cmd, body, reqid)
        vectors['cases'].append({
            'label': label,
            'cmd': cmd,
            'reqid': reqid,
            'pid': pid,
            'sid': sid,
            'start': start,
            'end': end,
            'stream': stream,
            'bodyHex': body.hex(),
            'innerHex': _inner_hex(m, cmd, body, reqid),
            'packetHex': packet.hex(),
        })

    # ---------- 用例组 2: _wrap 空 body（最短包） ----------
    empty_packet = m._wrap(25312, b'', 1)
    vectors['cases'].append({
        'label': 'wrap_empty_body',
        'cmd': 25312,
        'reqid': 1,
        'pid': '', 'sid': '', 'start': 0, 'end': 0, 'stream': '',
        'bodyHex': '',
        'innerHex': _inner_hex(m, 25312, b'', 1),
        'packetHex': empty_packet.hex(),
    })

    # ---------- 用例组 3: 类型全覆盖的字节级原语 ----------
    w = m.W()
    w.byte(0, 0)
    w.byte(1, 1)
    w.byte(-1, 2)
    w.byte(127, 3)
    w.short(-128, 4)
    w.short(128, 5)
    w.short(32767, 6)
    w.int(-32768, 7)
    w.int(32768, 8)
    w.int(2147483647, 9)
    w.long(-2147483649, 10)
    w.long(2147483648, 11)
    w.float(1.5, 12)
    w.double(-2.25, 13)
    w.string('', 14)                     # tag == 15 时的两字节头
    w.string('hello', 15)
    w.string('中文', 16)
    w.string('x' * 300, 17)              # > 255 走 type 7
    w.bytes(b'\x00\x01\xff', 18)
    w.struct(lambda ww: (ww.int(7, 0), ww.string('s', 1)), 19)
    w.list([1, 2, 3], 20, lambda ww, v: ww.int(v, 0))
    vectors['primitivesHex'] = w.out().hex()

    # ---------- 用例组 4: 一个真实 _head（含 _qua）字节 ----------
    w = m.W()
    w.struct(lambda ww: m._head(ww, 25312, 42), 0)
    vectors['headHex'] = w.out().hex()

    # ---------- 用例组 5: _unwrap 不认识的输入必须返回 None ----------
    vectors['unwrapBadHex'] = '00' * 100

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(vectors, f, indent=2, ensure_ascii=False, sort_keys=False)
        f.write('\n')

    print('wrote', OUT)
    print('primitives len =', len(bytes.fromhex(vectors['primitivesHex'])))
    print('head len       =', len(bytes.fromhex(vectors['headHex'])))
    for c in vectors['cases']:
        print(f"  {c['label']:<20} body={len(bytes.fromhex(c['bodyHex'])):>3}B packet={len(bytes.fromhex(c['packetHex'])):>3}B")
    return 0


if __name__ == '__main__':
    sys.exit(main())
